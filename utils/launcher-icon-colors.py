"""Writes the launcher icon colours: one adaptive icon and one activity-alias per app and colour.

Android cannot recolour a launcher icon at runtime, so every colour is its own disabled alias; the settings switch
one on and the others off (launcher/BuiltInApp.kt). Blue is the original icon and its hand-written alias
(`HomeAlias`, `MusicAlias`); this script writes the seven other colours. A new built-in app is one line in APPS
plus its entry in BuiltInApp. Run from the repository root: python3 utils/launcher-icon-colors.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
MANIFEST = ROOT / "app/src/main/AndroidManifest.xml"
HEADER = "<!-- Copyright (c) 2026 Ordo contributors; SPDX-License-Identifier: GPL-3.0-or-later -->\n" \
         "<!-- Generated by utils/launcher-icon-colors.py. Do not edit by hand. -->\n"

# key, alias suffix (IconColor.aliasSuffix), gradient start (the swatch), gradient end. Same order as IconColor.
COLORS = [
    ("blue", "Alias", "#2563EB", "#1D4ED8"),
    ("teal", "Teal", "#0F766E", "#115E59"),
    ("green", "Green", "#15803D", "#166534"),
    ("amber", "Amber", "#B45309", "#92400E"),
    ("red", "Red", "#DC2626", "#B91C1C"),
    ("pink", "Pink", "#BE185D", "#9D174D"),
    ("violet", "Violet", "#7C3AED", "#6D28D9"),
    ("graphite", "Graphite", "#374151", "#1F2937"),
]
# icon (mipmap of the blue original), foreground, monochrome, alias prefix, target activity, label
APPS = [
    ("launcher_icon", "launcher_icon_foreground_vector", "launcher_icon_monochrome",
     "me.zhanghai.android.files.launcher.Home", "me.zhanghai.android.files.home.HomeActivity", "app_name"),
    ("ic_launcher_music", "ic_launcher_music_foreground", "ic_launcher_music_foreground",
     "me.zhanghai.android.files.launcher.Music", "me.zhanghai.android.files.viewer.audio.MusicLauncherActivity",
     "launcher_music_label"),
]
BEGIN = "<!-- launcher-icon-colors: generated by utils/launcher-icon-colors.py, do not edit by hand -->"
END = "<!-- /launcher-icon-colors -->"


def contrast_with_white(hex_color):
    def channel(c):
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (int(hex_color[i:i + 2], 16) for i in (1, 3, 5))
    return 1.05 / (0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b) + 0.05)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main():
    # The white pictogram must stay readable on every background (WCAG 1.4.11 asks 3:1; we keep text-level 4.5:1).
    for key, _, start, end in COLORS:
        for color in (start, end):
            assert contrast_with_white(color) >= 4.5, f"{key} {color}: {contrast_with_white(color):.2f}:1"

    write(RES / "values/launcher_icon_palette.xml", '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER +
          "<resources>\n" + "".join(f'    <color name="launcher_icon_{k}">{s}</color>\n' for k, _, s, _ in COLORS) +
          "</resources>\n")
    aliases = []
    for key, suffix, start, end in COLORS[1:]:
        background = f"launcher_icon_background_{key}"
        write(RES / f"drawable/{background}.xml", '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER +
              '<shape xmlns:android="http://schemas.android.com/apk/res/android"\n'
              '    android:shape="rectangle">\n'
              f'    <gradient\n        android:angle="315"\n        android:endColor="{end}"\n'
              f'        android:startColor="@color/launcher_icon_{key}"\n        android:type="linear" />\n'
              '</shape>\n')
        for icon, foreground, monochrome, prefix, target, label in APPS:
            name = f"{icon}_{key}"
            write(RES / f"mipmap-anydpi-v26/{name}.xml", '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER +
                  '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                  f'    <background android:drawable="@drawable/{background}" />\n'
                  f'    <foreground android:drawable="@drawable/{foreground}" />\n'
                  f'    <monochrome android:drawable="@drawable/{monochrome}" />\n'
                  '</adaptive-icon>\n')
            # Android 7.x has no adaptive icons: a round version of the same two layers.
            write(RES / f"mipmap-anydpi/{name}.xml", '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER +
                  '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n'
                  '    <item>\n        <shape android:shape="oval">\n'
                  f'            <solid android:color="@color/launcher_icon_{key}" />\n'
                  '            <size android:width="108dp" android:height="108dp" />\n'
                  '        </shape>\n    </item>\n'
                  f'    <item android:drawable="@drawable/{foreground}" />\n'
                  '</layer-list>\n')
            aliases.append(
                f'        <activity-alias\n'
                f'            android:name="{prefix}{suffix}"\n'
                f'            android:enabled="false"\n'
                f'            android:exported="true"\n'
                f'            android:icon="@mipmap/{name}"\n'
                f'            android:label="@string/{label}"\n'
                f'            android:roundIcon="@mipmap/{name}"\n'
                f'            android:targetActivity="{target}">\n'
                f'            <intent-filter>\n'
                f'                <action android:name="android.intent.action.MAIN" />\n'
                f'                <category android:name="android.intent.category.LAUNCHER" />\n'
                f'            </intent-filter>\n'
                f'        </activity-alias>\n')

    manifest = MANIFEST.read_text()
    block = f"        {BEGIN}\n" + "".join(aliases) + f"        {END}\n"
    pattern = re.compile(r" *" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", re.DOTALL)
    if pattern.search(manifest):
        manifest = pattern.sub(lambda _: block, manifest)
    else:
        manifest = manifest.replace("    </application>", "\n" + block + "    </application>", 1)
    MANIFEST.write_text(manifest)
    print(f"{len(COLORS) - 1} colours x {len(APPS)} apps = {len(aliases)} aliases")


if __name__ == "__main__":
    main()
