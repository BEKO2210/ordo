    private fun openFileWithIntent(file: FileItem, withChooser: Boolean) {
        val path = file.path
        val mimeType = file.mimeType
        if (path.isArchivePath) {
            FileJobService.open(path, mimeType, withChooser, requireContext())
        } else {
            val intent = path.fileProviderUri.createViewIntent(mimeType)
                .addFlags(Intent.FLAG_GRANT_WRITE_URI_PERMISSION)
                .apply {
                    extraPath = path
                    // Token only after the intent is explicit. The chooser and other image apps must not see it.
                    if (!withChooser && mimeType.isImage) {
                        setClass(requireContext(), ImageViewerActivity::class.java)
                    }
                    maybeAddImageViewerActivityExtras(this, path, mimeType)
                    if (!withChooser) maybeAddAudioPlayerActivityExtras(this, path, mimeType)
                    if (!withChooser) maybeAddVideoPlayerActivityExtras(this, path, mimeType)
                    // PDFs open in Ordo's own viewer; "Open with" still offers every other app.
                    if (!withChooser && mimeType.value == "application/pdf") {
                        setClass(requireContext(), PdfViewerActivity::class.java)
                    } else if (!withChooser && mimeType.isPlayableAudio) {
                        setClass(requireContext(), AudioPlayerActivity::class.java)
                    } else if (!withChooser && mimeType.isVideo) {
                        setClass(requireContext(), VideoPlayerActivity::class.java)
                    }
                }
                .let {
                    if (withChooser) {
                        it.withChooser(
                            EditFileActivity::class.createIntent()
                                .putArgs(EditFileActivity.Args(path, mimeType)),
                            OpenFileAsDialogActivity::class.createIntent()
                                .putArgs(OpenFileAsDialogFragment.Args(path))
                        )
                    } else {
                        it
                    }
                }
            startActivitySafe(intent)
        }
    }

    private fun maybeAddImageViewerActivityExtras(intent: Intent, path: Path, mimeType: MimeType) {
        if (!mimeType.isImage) {
            return
        }
        var paths = mutableListOf<Path>()
        // We need the ordered list from our adapter instead of the list from FileListLiveData.
        for (index in 0..<adapter.itemCount) {
            val file = adapter.getItem(index)
            val filePath = file.path
            if (file.mimeType.isImage || filePath == path) {
                paths.add(filePath)
            }
        }
        var position = paths.indexOf(path)
        if (position == -1) {
            return
        }
        // HACK: Don't send too many paths to avoid TransactionTooLargeException.
        if (paths.size > IMAGE_VIEWER_ACTIVITY_PATH_LIST_SIZE_MAX) {
            val start = (position - IMAGE_VIEWER_ACTIVITY_PATH_LIST_SIZE_MAX / 2)
                .coerceIn(0, paths.size - IMAGE_VIEWER_ACTIVITY_PATH_LIST_SIZE_MAX)
            paths = paths.subList(start, start + IMAGE_VIEWER_ACTIVITY_PATH_LIST_SIZE_MAX)
            position -= start
        }
        ImageViewerActivity.putExtras(intent, paths, position)
    }

    private fun maybeAddAudioPlayerActivityExtras(intent: Intent, path: Path, mimeType: MimeType) {
        if (!mimeType.isPlayableAudio) return
        val audioPaths = buildList {
            for (index in 0..<adapter.itemCount) {
                val file = adapter.getItem(index)
                if (file.mimeType.isPlayableAudio) add(file.path)
            }
        }
        val queue = audioQueue(audioPaths, path) ?: return
        AudioPlayerActivity.putExtras(intent, queue.paths, queue.startIndex)
    }

    // The folder's videos in the list's order, cut like the music queue; formats ExoPlayer cannot play still open
    // here and get the player's "open with another app".
    private fun maybeAddVideoPlayerActivityExtras(intent: Intent, path: Path, mimeType: MimeType) {
        if (!mimeType.isVideo) return
        val videoPaths = buildList {
            for (index in 0..<adapter.itemCount) {
                val file = adapter.getItem(index)
                if (file.mimeType.isVideo) add(file.path)
            }
        }
        val queue = audioQueue(videoPaths, path) ?: return
        VideoPlayerActivity.putExtras(intent, queue.paths, queue.startIndex)
    }

