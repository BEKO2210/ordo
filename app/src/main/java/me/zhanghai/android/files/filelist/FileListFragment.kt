    private fun updateOverlayToolbar() {
        val files = viewModel.selectedFiles
        if (files.isEmpty()) {
            updateSelectionBar(null)
            if (overlayActionMode.isActive) {
                overlayActionMode.finish()
            }
            return
        }
        val pickOptions = viewModel.pickOptions
        if (pickOptions != null) {
            overlayActionMode.title = getString(R.string.file_list_select_title_format, files.size)
            overlayActionMode.setMenuResource(R.menu.file_list_pick)
            val menu = overlayActionMode.menu
            val isOpen = when (pickOptions.mode) {
                PickOptions.Mode.OPEN_FILE, PickOptions.Mode.OPEN_DIRECTORY -> true
                PickOptions.Mode.CREATE_FILE -> false
            }
            menu.findItem(R.id.action_open).isVisible = isOpen
            menu.findItem(R.id.action_create).isVisible = !isOpen
            menu.findItem(R.id.action_select_all).isVisible = pickOptions.allowMultiple
        } else {
            overlayActionMode.title = getString(R.string.file_list_select_title_format, files.size)
            overlayActionMode.setMenuResource(R.menu.file_list_select)
            val menu = overlayActionMode.menu
            // The selection bar hid these last time; start from visible, the rules below decide.
            SELECTION_BAR_ACTIONS.forEach { (_, itemId) -> menu.findItem(itemId).isVisible = true }
            val isAnyFileReadOnly = files.any { it.path.fileSystem.isReadOnly }
            menu.findItem(R.id.action_cut).isVisible = !isAnyFileReadOnly
            val areAllFilesArchivePaths = files.all { it.path.isArchivePath }
            val isAnyFileArchivePath = files.any { it.path.isArchivePath }
            menu.findItem(R.id.action_move_to).isVisible =
                !isAnyFileReadOnly && !isAnyFileArchivePath
            menu.findItem(R.id.action_copy_to).isVisible = !isAnyFileArchivePath
            // Only plain local files: a symbolic link would leave its target unprotected.
            menu.findItem(R.id.action_move_to_vault).isVisible = !isAnyFileReadOnly &&
                files.all { it.path.isLinuxPath && it.attributesNoFollowLinks.isRegularFile }
            menu.findItem(R.id.action_rename).isVisible = !isAnyFileReadOnly && !isAnyFileArchivePath
            menu.findItem(R.id.action_copy)
                .setIcon(
                    if (areAllFilesArchivePaths) {
                        R.drawable.extract_icon_control_normal_24dp
                    } else {
                        R.drawable.copy_icon_control_normal_24dp
                    }
                )
                .setTitle(
                    if (areAllFilesArchivePaths) {
                        R.string.file_list_select_action_extract
                    } else {
                        R.string.copy
                    }
                )
            menu.findItem(R.id.action_delete).isVisible = !isAnyFileReadOnly
            val areAllFilesArchiveFiles = files.all { it.isArchiveFile }
            menu.findItem(R.id.action_extract).isVisible = areAllFilesArchiveFiles
            val isCurrentPathReadOnly = viewModel.currentPath.fileSystem.isReadOnly
            menu.findItem(R.id.action_archive).isVisible = !isCurrentPathReadOnly
        }
        updateSelectionBar(if (pickOptions == null) overlayActionMode.menu else null)
        if (!overlayActionMode.isActive) {
            binding.appBarLayout.setExpanded(true)
            binding.appBarLayout.addOnOffsetChangedListener(
                AppBarLayoutExpandHackListener(binding.recyclerView)
            )
            overlayActionMode.start(object : ToolbarActionMode.Callback {
                override fun onToolbarActionModeMenuItemClicked(
                    toolbarActionMode: ToolbarActionMode,
                    item: MenuItem
                ): Boolean = onOverlayActionModeMenuItemClicked(item)

                override fun onToolbarActionModeFinished(toolbarActionMode: ToolbarActionMode) {
                    onOverlayActionModeFinished()
                }
            })
        }
    }

    // The main selection actions move from the top toolbar to a labeled bar at the bottom; the
    // menu stays the single source of truth for which actions apply.
    private fun updateSelectionBar(menu: Menu?) {
        val selectionBar = requireView().findViewById<ViewGroup>(R.id.selectionBar)
        if (menu != null && !selectionBar.isVisible) {
            // Slides up from the bottom edge instead of popping in.
            selectionBar.translationY = selectionBar.resources.displayMetrics.density * 72
            selectionBar.animate().translationY(0f).setDuration(220)
                .setInterpolator(DecelerateInterpolator()).start()
        }
        selectionBar.isVisible = menu != null
        binding.speedDialView.isVisible = menu == null && !isVirtualList
        if (menu == null) {
            return
        }
        for ((buttonId, itemId) in SELECTION_BAR_ACTIONS) {
            val item = menu.findItem(itemId)
            selectionBar.findViewById<MaterialButton>(buttonId).apply {
                isVisible = item.isVisible
                text = item.title
                icon = item.icon
                setOnClickListener { onOverlayActionModeMenuItemClicked(item) }
            }
            item.isVisible = false
        }
        selectionBar.findViewById<MaterialButton>(R.id.selectionMoreButton).apply {
            setText(R.string.file_list_selection_more)
            setIconResource(R.drawable.more_vertical_icon_white_24dp)
            setOnClickListener { showSelectionMoreMenu(it) }
        }
    }

    // The toolbar's own overflow would open at the top of the screen, far from the thumb that tapped "More" at the
    // bottom. Overflow style also overlaps its anchor, so a y-offset of 0 on the button covers the selection bar on a
    // short landscape screen. Same menu and clicks, anchored to the bar, no overlap, growing upwards.
    @SuppressLint("RestrictedApi")
    private fun showSelectionMoreMenu(anchor: View) {
        val menu = binding.overlayToolbar.menu as? MenuBuilder ?: return
        val selectionBar = requireView().findViewById<View>(R.id.selectionBar)
        val helper = MenuPopupHelper(
            requireContext(), menu, selectionBar, true, androidx.appcompat.R.attr.popupMenuStyle
        )
        helper.gravity = Gravity.END
        val barOnScreen = IntArray(2)
        val buttonOnScreen = IntArray(2)
        selectionBar.getLocationOnScreen(barOnScreen)
        anchor.getLocationOnScreen(buttonOnScreen)
        // popupMenuStyle has overlapAnchor false, so y = 0 flips the menu above the bar instead of over it.
        helper.show(
            SelectionMorePopup.showX(
                barOnScreen[0], buttonOnScreen[0], buttonOnScreen[0] + anchor.width,
                selectionBar.layoutDirection == View.LAYOUT_DIRECTION_RTL
            ),
            0
        )
        // Last item ("Select all") stays at the bar when the list is taller than the space above it.
        helper.listView?.isStackFromBottom = true
    }

