package me.zhanghai.android.files.legal

import java.io.File
import javax.xml.parsers.DocumentBuilderFactory
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.w3c.dom.Element

class LegalTextsTest {
    private fun arrays(directory: String): Map<String, List<String>> {
        val document = DocumentBuilderFactory.newInstance().newDocumentBuilder()
            .parse(File("src/main/res/$directory/legal.xml"))
        val nodes = document.getElementsByTagName("string-array")
        return (0 until nodes.length).associate { index ->
            val array = nodes.item(index) as Element
            val items = array.getElementsByTagName("item")
            array.getAttribute("name") to
                (0 until items.length).map { items.item(it).textContent }
        }
    }

    @Test
    fun everySectionHasTitleAndTextInBothLanguages() {
        val english = arrays("values")
        val german = arrays("values-de")
        for (kind in listOf("imprint", "privacy")) {
            val titles = english.getValue("legal_${kind}_titles")
            assertTrue(titles.isNotEmpty())
            for (texts in listOf(english, german)) {
                assertEquals(titles.size, texts.getValue("legal_${kind}_titles").size)
                assertEquals(titles.size, texts.getValue("legal_${kind}_texts").size)
            }
        }
    }

    // The web pages are generated by utils/legal-pages.py; this fails when they were not rebuilt.
    @Test
    fun webPagesCarryTheSameTexts() {
        val pages = mapOf(
            "values-de" to mapOf("imprint" to "impressum.html", "privacy" to "datenschutz.html"),
            "values" to mapOf("imprint" to "imprint.html", "privacy" to "privacy.html")
        )
        for ((directory, files) in pages) {
            val arrays = arrays(directory)
            for ((kind, file) in files) {
                val page = File("../docs/$file").readText()
                val texts = arrays.getValue("legal_${kind}_titles") +
                    arrays.getValue("legal_${kind}_texts")
                for (text in texts) {
                    // Line breaks become markup and links get wrapped, so compare plain sentences.
                    val firstSentence = text.replace("\\'", "'").substringBefore("\\n")
                        .substringBefore("http").substringBefore("nullmesh").trim()
                    assertTrue("$file lacks: $firstSentence", firstSentence in page)
                }
            }
        }
    }
}
