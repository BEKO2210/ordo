#!/usr/bin/env python3
"""Writes CommandNetLexicon.kt: every word list, pattern and text of the frozen net (rules2 + rules3) as Kotlin
literals, so the port's lexicon is the lab's byte for byte and nobody types it again.

    python3 export_tuned_lexicon.py <frozen lab dir> <out .kt>
"""
import os
import subprocess
import sys

LAB = os.path.abspath(sys.argv[1])
OUT = os.path.abspath(sys.argv[2])
sys.path.insert(0, LAB)
os.chdir(LAB)
import bench  # noqa: E402
import rules2 as R  # noqa: E402
import rules3  # noqa: E402
import phase0b  # noqa: E402
import phase0c  # noqa: E402


def s(x):
    return '"' + x.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n") + '"'


def strs(xs):
    return ", ".join(s(x) for x in xs)


def lst(xs):
    return f"listOf<String>({strs(xs)})"


def st(xs):
    return f"setOf<String>({strs(sorted(xs))})"


def mp(d, val):
    return "linkedMapOf(" + ", ".join(f"{s(k)} to {val(v)}" for k, v in d.items()) + ")"


commit = subprocess.run(["git", "log", "-1", "--format=%h", "--abbrev=8", "--", "rules2.py", "rules3.py", "bench.py", "p0_cases.py"], capture_output=True, text=True).stdout.strip()
L = []
add = lambda name, value: L.append(f"    val {name} = {value}")
add("NUM", mp(R.NUM, lambda v: f"{float(v)}"))
add("NUMW", s(R.NUMW))
add("MONTHS", mp(R.MONTHS, str))
add("WEEKDAYS", mp(R.WEEKDAYS, str))
add("SEASONS", mp(R.SEASONS, str))
add("HOLIDAYS", mp(R.HOLIDAYS, lambda v: f"Triple({v[0]}, {v[1]}, {v[2]})"))
add("UNIT", mp(R.UNIT, s))
add("UNITW", s(R.UNITW))
add("DAYS_PER", mp(R.DAYS_PER, str))
add("TYPES", mp(R.TYPES, lambda v: f"Pair({lst(v[0])}, {lst(v[1])})"))
add("EXT_WORDS", st(R.EXT_WORDS))
add("ALIAS", mp(R.ALIAS, lst))
add("WA", s(R.WA))
add("MESSENGER", mp(R.MESSENGER, lst))
for n in ("VOICE", "DOWNLOAD_VERB", "TAKEN", "SUBORD", "QUESTION_START", "MEMORY_SAY", "STORAGE", "HOL", "MON", "WD", "SEA",
          "YEAR", "LAST", "THIS", "POINT", "SU", "SN", "EXCL", "VAGUE_T", "VAGUE_S"):
    add(n, s(getattr(R, n)))
for n in ("STOP", "GENERIC", "VERB_EXACT", "NEGATOR", "EXT_WORDS", "STOP_AT", "DST_PREP", "SRC_PREP", "ACC_ART", "DAT_ART",
          "NEWQ", "FOLDERWORD", "FOLDERISH"):
    if n != "EXT_WORDS":
        add(n, st(getattr(R, n)))
add("ACTION_STEMS", mp(R.ACTION_STEMS, lst))
add("ACTION_EXACT", mp(R.ACTION_EXACT, s))
add("MEMORY", lst(R.MEMORY))
add("ASK", mp(R.ASK, s))
add("HEADS", lst(R.HEADS))
add("SIZEU", mp(R.SIZEU, lambda v: f"{float(v)}"))
add("SORTW", mp(R.SORTW, s))
add("GROUP", mp(R.GROUP, s))
add("HERE_WORDS", st(bench.HERE_WORDS))
add("FILE_KINDS", mp(bench.KINDS, st))
add("GUARD_IGNORE", st(rules3.GUARD_IGNORE))
add("NET_KINDS", lst(rules3.KINDS))
add("ASK_MODEL", s(rules3.ASK_MODEL))
add("SYSTEM_LORA", s(rules3.SYSTEM_LORA))
add("GRAMMAR_L", s(rules3.grammar()))
add("UNSUPPORTED", "listOf(" + ", ".join(f"Triple({s(a)}, {s(b)}, {s(c)})" for a, b, c in R.UNSUPPORTED) + ")")
add("SYSTEM_C", s(phase0c.system_c()))
add("GRAMMAR_C", s(phase0b.grammar(phase0c.FIELDS_C)))

src = f"""/*
 * Copyright (c) 2026 Ordo contributors
 * SPDX-License-Identifier: GPL-3.0-or-later
 */

package me.zhanghai.android.files.ai

/**
 * The frozen net's word lists, patterns and texts (tools/memory-lab rules2.py + prompt C of phase0c.py, rules3.py, lab commit {commit}).
 * Generated by tools/memory-lab/export_tuned_lexicon.py; never edit by hand, export again.
 */
@Suppress("SpellCheckingInspection", "MaxLineLength")
internal object CommandNetLexicon {{
""" + "\n".join(L) + "\n}\n"
open(OUT, "w", encoding="utf-8").write(src)
print(OUT, len(src), "chars, lab", commit)
